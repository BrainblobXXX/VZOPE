// ── утилиты ──────────────────────────────────────────────────

let idCounter = 1000
export const uid = () => `m${idCounter++}`

const min = 60_000
const hour = 60 * min
const day = 24 * hour

function t(minutesAgo: number): number {
  return Date.now() - minutesAgo * min
}

export function fmtTime(ts: number): string {
  const d = new Date(ts)
  return `${String(d.getHours()).padStart(2, '0')}:${String(d.getMinutes()).padStart(2, '0')}`
}

export function fmtTape(createdAt: number): string {
  const ms = Date.now() - createdAt
  const days = Math.floor(ms / day)
  const hours = Math.floor((ms % day) / hour)
  const mins = Math.floor((ms % hour) / min)
  if (days > 0) return `ПЛЁНКА: ${days}Д ${hours}Ч`
  if (hours > 0) return `ПЛЁНКА: ${hours}Ч ${mins}М`
  return `ПЛЁНКА: ${mins}М`
}

export const r = (
  emoji: ReactionEmoji,
  count: number,
  byMe = false,
): Reaction => ({ emoji, count, byMe })

