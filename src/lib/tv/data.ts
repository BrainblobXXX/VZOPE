// детерминированный мок: совпала ли реакция кандидата с моей на этом мемe
export function tasteAgrees(candidateId: string, memeId: string): boolean {
  const taste = CANDIDATE_TASTE[candidateId] ?? 0.5
  let h = 13
  const s = `${candidateId}:${memeId}`
  for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) % 9973
  return h % 100 < taste * 100
}

