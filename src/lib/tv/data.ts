function msg(
  authorId: string,
  text: string,
  minutesAgo: number,
  reactions: Reaction[] = [],
  extra?: Partial<Message>,
): Message {
  return {
    id: uid(),
    authorId,
    text,
    time: t(minutesAgo),
    reactions,
    ...extra,
  }
}

