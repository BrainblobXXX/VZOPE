// бесконечная лента: катаем каталог по кругу с детерминированным перемешиванием
export function buildFeed(): Meme[] {
  const out: Meme[] = []
  for (let lap = 0; lap < 12; lap++) {
    const lapMemes = memes.map((m, i) => ({ m, k: (i * 7 + lap * 3) % memes.length }))
    lapMemes.sort((a, b) => a.k - b.k)
    out.push(...lapMemes.map((x) => x.m))
  }
  return out
}

